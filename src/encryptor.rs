use crate::errors::AppError;
use crate::utils::base64;
use async_trait::async_trait;
use aws_sdk_kms::Client as KmsClient;
use aws_sdk_kms::primitives::Blob;
use aws_sdk_kms::types::DataKeySpec;
use ring::aead;
use ring::rand::{SecureRandom, SystemRandom};
use chacha20poly1305::{
    Key, XChaCha20Poly1305, XNonce,
    aead::{Aead, Generate, KeyInit},
};
use serde_derive::{Deserialize, Serialize};

#[derive(Serialize, Deserialize, Debug, Clone)]
pub struct EncryptedData {
    pub nonce: String,
    pub data: String,
}

#[async_trait]
pub trait Encryptor {
    async fn encrypt(&self, plaintext: &str) -> Result<String, AppError>;
    async fn decrypt(&self, ciphertext: &str) -> Result<String, AppError>;
}

#[derive(Clone)]
pub struct XChaCha20Encryptor {
    cipher: XChaCha20Poly1305,
}

impl XChaCha20Encryptor {
    pub fn from_key(key: &str) -> Result<XChaCha20Encryptor, AppError> {
        let key_bytes = key.as_bytes();
        let cipher_key = Key::try_from(key_bytes).map_err(|_| AppError::InvalidKeyLength(key_bytes.len()))?;
        let cipher = XChaCha20Poly1305::new(&cipher_key);

        Ok(XChaCha20Encryptor { cipher })
    }
}

#[async_trait]
impl Encryptor for XChaCha20Encryptor {
    async fn encrypt(&self, plaintext: &str) -> Result<String, AppError> {
        let nonce = XNonce::generate(); // 192-bits; unique per message
        let ciphertext = self.cipher.encrypt(&nonce, plaintext.as_bytes())?;

        let encrypted_data = EncryptedData {
            nonce: base64::encode_no_pad(nonce.as_slice()),
            data: base64::encode_no_pad(&ciphertext),
        };

        let json = serde_json::to_string(&encrypted_data)?;
        Ok(json)
    }

    async fn decrypt(&self, ciphertext: &str) -> Result<String, AppError> {
        let encrypted_data: EncryptedData = serde_json::from_str(ciphertext)?;

        let nonce_bytes = base64::decode_no_pad(encrypted_data.nonce.as_ref())?;
        let encrypted = base64::decode_no_pad(encrypted_data.data.as_ref())?;

        let nonce = XNonce::try_from(nonce_bytes.as_slice()).map_err(|_| {
            AppError::InvalidData(format!("Invalid nonce length: expected 24 bytes, got {} bytes", nonce_bytes.len()))
        })?;
        let plaintext = self.cipher.decrypt(&nonce, encrypted.as_slice())?;
        let decrypted = String::from_utf8(plaintext)?;

        Ok(decrypted)
    }
}

#[derive(Serialize, Deserialize, Debug, Clone)]
struct KmsEncryptedData {
    /// Data key encrypted by KMS
    key: String,
    nonce: String,
    data: String,
}

/// Envelope encryption: a data key is generated by KMS for each value, the value is encrypted locally with
/// AES-256-GCM (same cipher as the AWS Encryption SDK) and the KMS-encrypted data key is stored next to the ciphertext.
/// The result is a JSON string `{key, nonce, data}` with base64 (no padding) fields, same style as `XChaCha20Encryptor`.
#[derive(Clone)]
pub struct AWSKMSEncryptor {
    kms_client: KmsClient,
    key_id: String,
}

impl AWSKMSEncryptor {
    pub async fn new(kms_client: KmsClient, key_id: String) -> Result<AWSKMSEncryptor, AppError> {
        Ok(AWSKMSEncryptor { kms_client, key_id })
    }

    fn cipher_from_data_key(data_key: &[u8]) -> Result<aead::LessSafeKey, AppError> {
        let key = aead::UnboundKey::new(&aead::AES_256_GCM, data_key)
            .map_err(|_| AppError::InvalidKeyLength(data_key.len()))?;
        Ok(aead::LessSafeKey::new(key))
    }
}

#[async_trait]
impl Encryptor for AWSKMSEncryptor {
    async fn encrypt(&self, plaintext: &str) -> Result<String, AppError> {
        let data_key = self
            .kms_client
            .generate_data_key()
            .key_id(&self.key_id)
            .key_spec(DataKeySpec::Aes256)
            .send()
            .await
            .map_err(|e| AppError::EncryptionError(format!("AWS KMS generate data key failed: {}", e)))?;

        let plaintext_key = data_key
            .plaintext
            .ok_or_else(|| AppError::EncryptionError("No plaintext key in KMS response".to_string()))?;
        let encrypted_key = data_key
            .ciphertext_blob
            .ok_or_else(|| AppError::EncryptionError("No encrypted key in KMS response".to_string()))?;

        let cipher = Self::cipher_from_data_key(plaintext_key.as_ref())?;
        // A fresh data key is used for every value, so a random 96-bit nonce is safe
        let mut nonce_bytes = [0u8; aead::NONCE_LEN];
        SystemRandom::new()
            .fill(&mut nonce_bytes)
            .map_err(|_| AppError::EncryptionError("Failed to generate nonce".to_string()))?;

        let mut in_out = plaintext.as_bytes().to_vec();
        cipher
            .seal_in_place_append_tag(aead::Nonce::assume_unique_for_key(nonce_bytes), aead::Aad::empty(), &mut in_out)
            .map_err(|_| AppError::EncryptionError("AES-256-GCM encryption failed".to_string()))?;

        let encrypted_data = KmsEncryptedData {
            key: base64::encode_no_pad(encrypted_key.as_ref()),
            nonce: base64::encode_no_pad(&nonce_bytes),
            data: base64::encode_no_pad(&in_out),
        };

        Ok(serde_json::to_string(&encrypted_data)?)
    }

    async fn decrypt(&self, ciphertext: &str) -> Result<String, AppError> {
        let encrypted_data: KmsEncryptedData = serde_json::from_str(ciphertext)?;

        let encrypted_key = base64::decode_no_pad(encrypted_data.key.as_bytes())?;
        let nonce_bytes = base64::decode_no_pad(encrypted_data.nonce.as_bytes())?;
        let mut in_out = base64::decode_no_pad(encrypted_data.data.as_bytes())?;

        let response = self
            .kms_client
            .decrypt()
            .key_id(&self.key_id)
            .ciphertext_blob(Blob::new(encrypted_key))
            .send()
            .await
            .map_err(|e| AppError::EncryptionError(format!("AWS KMS decrypt data key failed: {}", e)))?;

        let plaintext_key = response
            .plaintext
            .ok_or_else(|| AppError::EncryptionError("No plaintext key in KMS response".to_string()))?;

        let cipher = Self::cipher_from_data_key(plaintext_key.as_ref())?;
        let nonce = aead::Nonce::try_assume_unique_for_key(&nonce_bytes).map_err(|_| {
            AppError::InvalidData(format!(
                "Invalid nonce length: expected {} bytes, got {} bytes",
                aead::NONCE_LEN,
                nonce_bytes.len()
            ))
        })?;
        let plaintext = cipher
            .open_in_place(nonce, aead::Aad::empty(), &mut in_out)
            .map_err(|_| AppError::EncryptionError("AES-256-GCM decryption failed".to_string()))?;

        Ok(String::from_utf8(plaintext.to_vec())?)
    }
}

#[cfg(test)]
mod tests {
    use std::env;

    use crate::encryptor::{AWSKMSEncryptor, Encryptor, XChaCha20Encryptor};

    #[tokio::test]
    async fn encrypt_decrypt_string() -> Result<(), Box<dyn std::error::Error>> {
        let key_plaintext = "plain text key which should be s";

        let encryptor = XChaCha20Encryptor::from_key(&key_plaintext)?;

        let original = "plain text string";
        let encrypted = encryptor.encrypt(original).await?;

        let decrypted = encryptor.decrypt(&encrypted).await?;

        assert_eq!(decrypted, original);
        Ok(())
    }

    #[tokio::test(flavor = "multi_thread")]
    async fn encrypt_decrypt_string_with_aws_kms() -> Result<(), Box<dyn std::error::Error>> {
        let kms_key_id = match env::var("KMS_KEY_ID") {
            Ok(key) => key,
            Err(_) => {
                println!("SKIPPED: KMS_KEY_ID environment variable not set");
                return Ok(());
            }
        };

        let sdk_config = aws_config::load_defaults(aws_config::BehaviorVersion::latest()).await;
        let kms_client = aws_sdk_kms::Client::new(&sdk_config);

        let encryptor = AWSKMSEncryptor::new(kms_client, kms_key_id.to_string()).await?;

        let original = "plain text string for AWS KMS encryption test";

        let encrypted = encryptor.encrypt(original).await?;

        assert!(!encrypted.is_empty(), "Encrypted data should not be empty");

        let decryptor_kms_client = aws_sdk_kms::Client::new(&sdk_config);
        let decryptor = AWSKMSEncryptor::new(decryptor_kms_client, kms_key_id.to_string()).await?;

        let decrypted = decryptor.decrypt(&encrypted).await?;

        assert_eq!(decrypted, original);

        Ok(())
    }

    #[tokio::test]
    async fn encrypt_decrypt_string_with_mocked_kms() -> Result<(), Box<dyn std::error::Error>> {
        use aws_sdk_kms::Client;
        use aws_sdk_kms::operation::decrypt::DecryptOutput;
        use aws_sdk_kms::operation::generate_data_key::GenerateDataKeyOutput;
        use aws_sdk_kms::primitives::Blob;
        use aws_smithy_mocks::{RuleMode, mock, mock_client};

        let data_key = b"0123456789abcdef0123456789abcdef".to_vec();
        let wrapped_key = b"wrapped-data-key".to_vec();

        let generate_key_data = data_key.clone();
        let generate_key_wrapped = wrapped_key.clone();
        let generate_rule = mock!(Client::generate_data_key)
            .match_requests(|req| req.key_id() == Some("test-key-id"))
            .then_output(move || {
                GenerateDataKeyOutput::builder()
                    .plaintext(Blob::new(generate_key_data.clone()))
                    .ciphertext_blob(Blob::new(generate_key_wrapped.clone()))
                    .build()
            });

        let expected_wrapped = wrapped_key.clone();
        let decrypt_rule = mock!(Client::decrypt)
            .match_requests(move |req| {
                req.key_id() == Some("test-key-id")
                    && req.ciphertext_blob().map(|b| b.as_ref()) == Some(expected_wrapped.as_slice())
            })
            .then_output(move || DecryptOutput::builder().plaintext(Blob::new(data_key.clone())).build());

        let kms_client = mock_client!(aws_sdk_kms, RuleMode::MatchAny, &[&generate_rule, &decrypt_rule]);
        let encryptor = AWSKMSEncryptor::new(kms_client, "test-key-id".to_string()).await?;

        let original = "plain text string";
        let encrypted = encryptor.encrypt(original).await?;
        assert!(!encrypted.contains(original));

        let decrypted = encryptor.decrypt(&encrypted).await?;
        assert_eq!(decrypted, original);
        Ok(())
    }
}
